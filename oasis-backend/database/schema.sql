CREATE TABLE IF NOT EXISTS users (
  id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
  name VARCHAR(150) NOT NULL,
  email VARCHAR(150) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role ENUM('MAHASISWA','DOSEN','DOSEN_PENGAMPU','LABORAN','KEPALA_LABORATORIUM') NOT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS rooms (
  id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
  name VARCHAR(100) NOT NULL,
  capacity INT UNSIGNED,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS course_schedules (
  id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
  room_id BIGINT UNSIGNED NOT NULL,
  course_name VARCHAR(150) NOT NULL,
  day_of_week TINYINT UNSIGNED NOT NULL,
  start_time TIME NOT NULL,
  end_time TIME NOT NULL,
  valid_from DATE NULL,
  valid_until DATE NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_schedule_room FOREIGN KEY (room_id) REFERENCES rooms(id),
  INDEX idx_schedule_room_time (room_id, day_of_week, start_time, end_time)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS room_bookings (
  id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
  room_id BIGINT UNSIGNED NOT NULL,
  user_id BIGINT UNSIGNED NOT NULL,
  borrower_name VARCHAR(150) NULL,
  borrower_email VARCHAR(150) NULL,
  start_at DATETIME NOT NULL,
  end_at DATETIME NOT NULL,
  purpose VARCHAR(500) NOT NULL,
  status ENUM('MENUNGGU','DISETUJUI','DITOLAK','SELESAI','DIBATALKAN') NOT NULL DEFAULT 'MENUNGGU',
  rejection_reason VARCHAR(500) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_booking_room FOREIGN KEY (room_id) REFERENCES rooms(id),
  CONSTRAINT fk_booking_user FOREIGN KEY (user_id) REFERENCES users(id),
  INDEX idx_booking_room_time (room_id, start_at, end_at),
  INDEX idx_booking_status (status)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS equipment_types (
  id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
  name VARCHAR(150) NOT NULL,
  category ENUM('BIASA','KHUSUS') NOT NULL DEFAULT 'BIASA',
  description VARCHAR(500),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS equipment_units (
  id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
  equipment_type_id BIGINT UNSIGNED NOT NULL,
  unit_code VARCHAR(100) NOT NULL UNIQUE,
  condition_status ENUM('BAIK','RUSAK','HILANG','PERLU_PERBAIKAN') NOT NULL DEFAULT 'BAIK',
  availability_status ENUM('TERSEDIA','DIPESAN','DIPINJAM','TIDAK_TERSEDIA') NOT NULL DEFAULT 'TERSEDIA',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_unit_type FOREIGN KEY (equipment_type_id) REFERENCES equipment_types(id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS equipment_loans (
  id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
  user_id BIGINT UNSIGNED NOT NULL,
  borrower_name VARCHAR(150) NULL,
  borrower_email VARCHAR(150) NULL,
  loan_type ENUM('BIASA','KHUSUS') NOT NULL,
  purpose VARCHAR(500) NOT NULL,
  start_date DATE NOT NULL,
  due_date DATE NOT NULL,
  status ENUM('MENUNGGU_DOSEN','MENUNGGU_LABORAN','DISETUJUI','DITOLAK','SEDANG_DIPINJAM','SELESAI','DIBATALKAN') NOT NULL DEFAULT 'MENUNGGU_LABORAN',
  rejection_reason VARCHAR(500) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_loan_user FOREIGN KEY (user_id) REFERENCES users(id),
  INDEX idx_loan_user_status (user_id, status),
  INDEX idx_loan_due_date (due_date)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS loan_items (
  id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
  loan_id BIGINT UNSIGNED NOT NULL,
  unit_id BIGINT UNSIGNED NOT NULL,
  quantity TINYINT UNSIGNED NOT NULL DEFAULT 1,
  handed_over_at DATETIME NULL,
  returned_at DATETIME NULL,
  return_condition ENUM('BAIK','RUSAK','HILANG','PERLU_PERBAIKAN') NULL,
  CONSTRAINT fk_loan_item_loan FOREIGN KEY (loan_id) REFERENCES equipment_loans(id) ON DELETE CASCADE,
  CONSTRAINT fk_loan_item_unit FOREIGN KEY (unit_id) REFERENCES equipment_units(id),
  INDEX idx_loan_item_loan (loan_id),
  INDEX idx_loan_item_unit (unit_id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS approvals (
  id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
  loan_id BIGINT UNSIGNED NOT NULL,
  approver_id BIGINT UNSIGNED NOT NULL,
  approver_role ENUM('DOSEN_PENGAMPU','LABORAN','KEPALA_LABORATORIUM') NOT NULL,
  decision ENUM('MENUNGGU','DISETUJUI','DITOLAK') NOT NULL DEFAULT 'MENUNGGU',
  note VARCHAR(500) NULL,
  decided_at DATETIME NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_approval_loan FOREIGN KEY (loan_id) REFERENCES equipment_loans(id) ON DELETE CASCADE,
  CONSTRAINT fk_approval_user FOREIGN KEY (approver_id) REFERENCES users(id),
  INDEX idx_approval_loan_role (loan_id, approver_role)
) ENGINE=InnoDB;
